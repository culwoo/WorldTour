/**
 * Orbit(3D photo ring) texture pipeline.
 *
 * 1. Generates GPU-friendly ring thumbnails (long edge 1024px) into
 *    public/images/ring/ — these are what the 3D ring renders with.
 *    Full-resolution originals are only loaded on demand when a card is
 *    docked (clicked), keeping VRAM usage ~8x lower.
 * 2. Emits src/data/imageMeta.ts with the TRUE pixel dimensions and aspect
 *    ratio of every image, so 3D card geometry never distorts a photo.
 *
 * Usage: node scripts/build-orbit-textures.mjs
 */
import path from 'node:path';
import { promises as fs } from 'node:fs';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const imagesDir = path.join(projectRoot, 'public', 'images');
const ringDir = path.join(imagesDir, 'ring');
const metaFilePath = path.join(projectRoot, 'src', 'data', 'imageMeta.ts');

const LONG_EDGE = Number(process.env.RING_LONG_EDGE ?? 1024);
const QUALITY = Number(process.env.RING_WEBP_QUALITY ?? 82);
const EFFORT = Number(process.env.RING_WEBP_EFFORT ?? 6);

const formatKB = (bytes) => `${(bytes / 1024).toFixed(0)}KB`;

const main = async () => {
    await fs.mkdir(ringDir, { recursive: true });

    const entries = await fs.readdir(imagesDir, { withFileTypes: true });
    const webpFiles = entries
        .filter((e) => e.isFile() && /\.webp$/i.test(e.name))
        .map((e) => e.name)
        .sort();

    if (webpFiles.length === 0) {
        console.log('No .webp files found in public/images.');
        return;
    }

    const meta = {};
    let thumbTotal = 0;

    for (const name of webpFiles) {
        const inputPath = path.join(imagesDir, name);
        const outputPath = path.join(ringDir, name);

        const info = await sharp(inputPath).metadata();
        const width = info.width ?? 1;
        const height = info.height ?? 1;
        meta[name] = { width, height, aspect: Number((width / height).toFixed(4)) };

        const resize = width >= height
            ? { width: LONG_EDGE, withoutEnlargement: true }
            : { height: LONG_EDGE, withoutEnlargement: true };

        await sharp(inputPath)
            .resize(resize)
            .webp({ quality: QUALITY, effort: EFFORT })
            .toFile(outputPath);

        const stat = await fs.stat(outputPath);
        thumbTotal += stat.size;
        console.log(`ring/${name} ${formatKB(stat.size)} (${width}x${height}, aspect ${meta[name].aspect})`);
    }

    const ts = [
        '// AUTO-GENERATED by scripts/build-orbit-textures.mjs — do not edit by hand.',
        '// Regenerate with: node scripts/build-orbit-textures.mjs',
        '',
        'export interface ImageMeta {',
        '    width: number;',
        '    height: number;',
        '    aspect: number;',
        '}',
        '',
        `export const imageMeta: Record<string, ImageMeta> = ${JSON.stringify(meta, null, 4)};`,
        '',
        '/** Ring thumbnail (long edge 1024px) used by the 3D scene. */',
        "export const ringTextureUrl = (url: string): string => url.replace('/images/', '/images/ring/');",
        '',
    ].join('\n');

    await fs.writeFile(metaFilePath, ts, 'utf8');

    console.log(`\n${webpFiles.length} thumbnails -> public/images/ring (${formatKB(thumbTotal)} total)`);
    console.log(`Meta -> src/data/imageMeta.ts`);
};

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
